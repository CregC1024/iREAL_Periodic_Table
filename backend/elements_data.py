def _grid_position(z: int, period: int, group):
    """Return (row, col) in an 18x10 layout; f-block goes to rows 9 and 10."""
    if 57 <= z <= 71:
        return 9, z - 57 + 3
    if 89 <= z <= 103:
        return 10, z - 89 + 3
    return period, group


